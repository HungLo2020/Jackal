#!/usr/bin/env python3
"""Optionally reproduce the native game's WAV assets from a pinned offline reference.

Legacy execution code and ROM-derived bytes exist only in a temporary directory.
This script is never invoked by cargo build/run or the native game.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

REFERENCE_COMMIT = "e8fc3391d5b27fcd98b82fd27984141840449708"
ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
NAMES = {
    0x09: "machine_gun", 0x11: "grenade", 0x15: "explosion",
    0x25: "player_death", 0x1D: "rescue", 0x21: "pickup", 0x1F: "delivery",
    0x23: "boss", 0x30: "title", 0x34: "briefing", 0x38: "stage_1",
    0x3C: "stage_2", 0x40: "stage_3", 0x44: "alternate_stage",
    0x48: "helicopter", 0x4C: "victory", 0x50: "game_over", 0x54: "ending",
}
NOTES = [
    "All 43 top-level records in the original sound table, including music, effects, pause tone, and control sounds. Constituent channel records are combined by the original sequencer.",
    "Loop boundaries detected from repeated complete sequencer state; full intro preserved and repeat begins at loop_start_sample. Non-looping clips include 15 frames of release tail.",
    "Offline five-channel synthesis includes both original DMC samples. Frame-timed synthesis approximates analog filtering; WAV playback requires no ROM, sequencer, or console state.",
]


def restore_reference(directory):
    for name in ("Cargo.toml", "Cargo.lock", "src/audio.rs", "src/game.rs",
                 "src/video.rs", "assets/game-data.bin", "generated/native_game.rs"):
        data = subprocess.check_output(
            ["git", "show", f"{REFERENCE_COMMIT}:{name}"], cwd=ROOT)
        target = directory / name
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
    for module in ("audio", "game"):
        with (directory / "src" / f"{module}.rs").open("a") as stream:
            stream.write("\n" + (HERE / f"{module}_export_methods.rs").read_text())
    shutil.copyfile(HERE / "audio_export_main.rs", directory / "src/main.rs")


def finalize_assets(directory):
    manifest = directory / "audio.json"
    data = json.loads(manifest.read_text())
    for entry in data["sounds"]:
        name = NAMES.get(entry["command"], f'effect_{entry["command"]:02x}')
        old = directory / entry["file"]
        new = directory / "audio" / f"{name}.wav"
        old.rename(new)
        entry["file"] = f"audio/{name}.wav"
        entry["name"] = name
        entry["duration_seconds"] = round(entry["samples"] / 44100, 6)
    data["export_notes"] = NOTES
    manifest.write_text(json.dumps(data, indent=2) + "\n")
    return [Path("audio.json")] + [Path(e["file"]) for e in data["sounds"]]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=ROOT / "assets",
                        help="destination asset directory (default: repository assets)")
    parser.add_argument("--check", action="store_true",
                        help="compare regenerated bytes with destination; do not modify assets")
    parser.add_argument("--online", action="store_true",
                        help="allow Cargo to fetch the pinned dependency versions")
    parser.add_argument("--target-dir", type=Path, default=ROOT / "target/reference-audio",
                        help="reusable Cargo compilation cache")
    args = parser.parse_args()
    destination = args.output.resolve()
    with tempfile.TemporaryDirectory(prefix="jackal-audio-reference-") as temporary:
        temporary = Path(temporary)
        reference, exported = temporary / "reference", temporary / "exported"
        restore_reference(reference)
        env = dict(os.environ, CARGO_TARGET_DIR=str(args.target_dir.resolve()))
        command = ["cargo", "run", "--locked", "--manifest-path", str(reference / "Cargo.toml")]
        if not args.online:
            command.append("--offline")
        subprocess.run(command + ["--", str(exported)], env=env, check=True, cwd=reference)
        files = finalize_assets(exported)
        mismatches = []
        for relative in files:
            source, target = exported / relative, destination / relative
            if args.check:
                if not target.exists() or hashlib.sha256(source.read_bytes()).digest() != hashlib.sha256(target.read_bytes()).digest():
                    mismatches.append(str(relative))
            else:
                target.parent.mkdir(parents=True, exist_ok=True)
                shutil.copyfile(source, target)
        if mismatches:
            raise SystemExit("Regenerated assets differ: " + ", ".join(mismatches))
        print(f"{'Verified' if args.check else 'Exported'} {len(files)-1} WAV assets and audio.json")


if __name__ == "__main__":
    main()
